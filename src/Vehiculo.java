public class Vehiculo {

    // Atributos
    protected String tipo;

    // Métodos
    // Constructor
    public Vehiculo(String tipo) {
        this.tipo = tipo;
    }

    //Getters
    public String getTipo(){
        return tipo;
    }

    //Setters
    public void setTipo(String tipo) {
        this.tipo = tipo;
    }
    
}
